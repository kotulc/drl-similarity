from drl_similarity.config import load_config
from drl_similarity.dashboard import data as dd
from drl_similarity.dashboard.pages import PAGE_ORDER
from drl_similarity.errors import ArtifactError
from drl_similarity.tables import SUMMARY_COLUMNS


FIXTURE_CONFIG = Path(__file__).resolve().parents[1] / "fixtures" / "study" / "study.yaml"

pytestmark = pytest.mark.skipif(
    not FIXTURE_CONFIG.exists(),
    reason="fixture study missing; run: python scripts/generate_fixture_study.py",
)


@pytest.fixture(scope="module")
def data() -> dd.DashboardData:
    return dd.load_dashboard_data(load_config(FIXTURE_CONFIG, expected_kind="study"))


def test_fixture_validates() -> None:
    dd.validate_dashboard_artifacts(load_config(FIXTURE_CONFIG, expected_kind="study"))


def test_loaded_tables_match_contract(data: dd.DashboardData) -> None:
    assert data.study.study_id == "fixture-study-v1"
    assert data.study.labels == ("baseline", "danger", "goal")
    assert data.study.capabilities == ("weak", "medium", "strong")
    assert set(SUMMARY_COLUMNS) <= set(data.summaries.columns)
    assert len(data.summaries) and len(data.cross_checkpoint) and len(data.frame_pairs) and len(data.embeddings)
    assert set(data.selected["capability"]) == {"weak", "medium", "strong"}
    assert data.study.synthetic is True
    codes = {issue.code for issue in data.quality}
    assert {"synthetic_data", "single_seed"} <= codes
    assert data.status == "warning"


def test_case_cell_filters(data: dd.DashboardData) -> None:
    run_id = str(data.runs["run_id"].iloc[0])
    within = dd.case_cell_rows(
        data, run_id=run_id, checkpoint="strong", layer="policy_features",
        pair_set="cross_clip_aligned_step", row="danger", column="danger",
    )  # fmt: skip
    between = dd.case_cell_rows(
        data, run_id=run_id, checkpoint="strong", layer="policy_features",
        pair_set="cross_clip_aligned_step", row="danger", column="goal",
    )  # fmt: skip
    assert set(within) == set(dd.CELL_METRICS)
    assert set(between) == set(dd.CELL_METRICS)
    assert within["cosine"]["scope"] == "within_scenario"
    assert between["cosine"]["scope"] == "between_scenario"
    assert within["linear_cka"]["pair_set"] == "clip_aligned_steps"
    mirrored = dd.case_cell_rows(
        data, run_id=run_id, checkpoint="strong", layer="policy_features",
        pair_set="cross_clip_aligned_step", row="goal", column="danger",
    )  # fmt: skip
    assert mirrored["cosine"]["estimate"] == pytest.approx(between["cosine"]["estimate"])


def test_frame_pair_lookup_is_symmetric(data: dd.DashboardData) -> None:
    run_id = str(data.runs["run_id"].iloc[0])
    rows = dd.frames_for_case(data, "danger", 3)
    columns = dd.frames_for_case(data, "goal", 3)
    assert len(rows) == 3 and len(columns) == 3
    a, b = rows.iloc[0], columns.iloc[2]
    kwargs = {"run_id": run_id, "checkpoint": "strong", "layer": "policy_features"}
    forward = dd.frame_pair_values(
        data, clip_a=a["clip_id"], step_a=int(a["step"]), clip_b=b["clip_id"], step_b=int(b["step"]), **kwargs
    )
    backward = dd.frame_pair_values(
        data, clip_a=b["clip_id"], step_a=int(b["step"]), clip_b=a["clip_id"], step_b=int(a["step"]), **kwargs
    )
    assert set(forward) == set(dd.CELL_METRICS)
    assert forward == backward


def test_missing_metrics_reports_regeneration_command(tmp_path: Path) -> None:
    import shutil

    target = tmp_path / "study"
    shutil.copytree(FIXTURE_CONFIG.parent, target)
    shutil.rmtree(target / "results" / "fixture-study-v1" / "metrics")
    with pytest.raises(ArtifactError) as excinfo:
        dd.validate_dashboard_artifacts(load_config(target / "study.yaml", expected_kind="study"))
    assert "drl-sim analyze" in str(excinfo.value)


def test_corrupt_table_is_reported(tmp_path: Path) -> None:
    import shutil

    target = tmp_path / "study"
    shutil.copytree(FIXTURE_CONFIG.parent, target)
    table = target / "results" / "fixture-study-v1" / "metrics" / "summaries.parquet"
    table.write_bytes(table.read_bytes()[:-64] + b"\0" * 64)
    with pytest.raises(ArtifactError) as excinfo:
        dd.validate_dashboard_artifacts(load_config(target / "study.yaml", expected_kind="study"))
    assert "failed verification" in str(excinfo.value)


def _page_script(module_name: str, config_path: str) -> None:
    import importlib

    import streamlit as st

    from drl_similarity.config import load_config
    from drl_similarity.dashboard import components as ui
    from drl_similarity.dashboard.data import load_dashboard_data

    st.set_page_config(layout="wide")
    loaded = load_dashboard_data(load_config(config_path, expected_kind="study"))
    ui.ensure_state(loaded)
    importlib.import_module(f"drl_similarity.dashboard.pages.{module_name}").render(loaded)


@pytest.mark.parametrize("module_name", [page_id for page_id, _ in PAGE_ORDER])
def test_page_renders_without_exception(module_name: str) -> None:
    from streamlit.testing.v1 import AppTest

    app = AppTest.from_function(_page_script, args=(module_name, str(FIXTURE_CONFIG)), default_timeout=120)
    app.run()
    assert not app.exception, [str(item.value) for item in app.exception]
    assert not [item.value for item in app.error if "could not" in str(item.value)]


def test_matrix_page_axis_interactions() -> None:
    from streamlit.testing.v1 import AppTest

    from drl_similarity.dashboard import state

    app = AppTest.from_function(_page_script, args=("similarity_matrix", str(FIXTURE_CONFIG)), default_timeout=120)
    app.run()
    assert not app.exception
    assert app.session_state[state.ROW_SCENARIO] == "danger"
    assert app.session_state[state.COLUMN_SCENARIO] == "danger"

    # Changing the column selector keeps the row case and resets the frame selection.
    app.button(key="frame_open_0_2").click().run()
    assert (app.session_state[state.ROW_FRAME], app.session_state[state.COLUMN_FRAME]) == (0, 2)
    app.selectbox(key=state.COLUMN_SCENARIO).select("goal").run()
    assert app.session_state[state.ROW_SCENARIO] == "danger"
    assert app.session_state[state.COLUMN_SCENARIO] == "goal"
    assert (app.session_state[state.ROW_FRAME], app.session_state[state.COLUMN_FRAME]) == (1, 1)

    # A case-cell click synchronises both selectors.
    app.button(key="case_open_baseline_goal").click().run()
    assert app.session_state[state.ROW_SCENARIO] == "baseline"
    assert app.session_state[state.COLUMN_SCENARIO] == "goal"
    assert app.selectbox(key=state.ROW_SCENARIO).value == "baseline"

    # Swapping axes exchanges cases and transposes the selected frame pair.
    app.button(key="frame_open_0_2").click().run()
    app.button(key="matrix_swap").click().run()
    assert app.session_state[state.ROW_SCENARIO] == "goal"
    assert app.session_state[state.COLUMN_SCENARIO] == "baseline"
    assert (app.session_state[state.ROW_FRAME], app.session_state[state.COLUMN_FRAME]) == (2, 0)
    assert not app.exception
