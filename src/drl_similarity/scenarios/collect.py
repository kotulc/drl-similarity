"""Collect candidate scenario clips from a selected checkpoint.

The collector rolls out the configured checkpoint on the collection seeds and
captures a fixed-length window around each candidate anchor event. It writes:

``<manifest dir>/<manifest stem>/``
    ``observations.npz``            canonical uint8 frame stacks keyed by clip id
    ``candidates/source_rgb.npz``   optional emulator RGB frames per candidate
    ``candidates/episodes/*.npz``   full per-step actions, rewards, lives, flags
    ``candidates/contact_sheets/``  one PNG per candidate for curation
    ``candidates/previews/``        optional MP4 per candidate
    ``candidates/candidates.json``  collection summary and skipped-window counts

and a manifest template at ``scenarios.manifest`` in which every clip is
``review_status: pending``. Labels are never approved automatically.
"""

from __future__ import annotations

import json
import zipfile
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import numpy as np

from drl_similarity.agents.registry import get_algorithm_adapter
from drl_similarity.artifacts.manifest import sha256_file
from drl_similarity.config import ResolvedConfig, StudyConfig
from drl_similarity.environments.atari import make_environment
from drl_similarity.errors import CheckpointError, ScenarioError
from drl_similarity.logging import get_logger, log_extra
from drl_similarity.scenarios.schema import (
    ClipRecord,
    CollectorInfo,
    ScenarioManifest,
    assign_splits,
    dump_manifest,
    observation_sha256,
    utc_now,
)
from drl_similarity.study_io import (
    RunInfo,
    load_run,
    require_study,
    resolve_device,
    scenario_data_dir,
)


#: Anchor events the collector can detect during a rollout (mirrors CandidateWindowConfig.anchor).
ANCHOR_EVENTS: tuple[str, ...] = ("life_start", "life_lost", "positive_goal_event")

_TEMPLATE_HEADER = """Scenario manifest TEMPLATE generated by `drl-sim collect-scenarios`.

Every clip below is an unreviewed candidate. For each clip, inspect the contact
sheet (and preview video if present) under the candidates directory, then set
  review_status: approved | rejected
and record the reviewer name(s) in `curator` (comma separated).
Review labels without looking at activation or metric results.
Then run: drl-sim validate-scenarios --config <study.yaml>"""


@dataclass
class _PendingWindow:
    label: str
    anchor_event: str
    anchor_step: int
    anchor_reward: float
    start: int
    end: int


@dataclass
class _EpisodeState:
    episode_id: str
    seed: int
    actions: list[int] = field(default_factory=list)
    rewards: list[float] = field(default_factory=list)
    lives: list[int] = field(default_factory=list)
    terminated: list[bool] = field(default_factory=list)
    truncated: list[bool] = field(default_factory=list)
    events: dict[int, list[str]] = field(default_factory=dict)


class _NpzWriter:
    """Append arrays to an ``.npz`` archive one at a time (bounded memory)."""

    def __init__(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        self.path = path
        self._zip = zipfile.ZipFile(path, mode="w", compression=zipfile.ZIP_DEFLATED, allowZip64=True)
        self.count = 0

    def add(self, key: str, array: np.ndarray) -> None:
        with self._zip.open(f"{key}.npy", mode="w", force_zip64=True) as handle:
            np.lib.format.write_array(handle, np.ascontiguousarray(array), allow_pickle=False)
        self.count += 1

    def close(self) -> None:
        self._zip.close()


def _newest_frame(observation: np.ndarray) -> np.ndarray:
    """Most recent 2D frame of a (possibly stacked) observation, for previews only."""
    frame = np.asarray(observation)
    while frame.ndim > 2:
        frame = frame[-1]
    return frame


def _contact_sheet(frames: np.ndarray, *, columns: int = 8, scale: int = 2) -> Any:
    from PIL import Image

    tiles = [_newest_frame(frame) for frame in frames]
    height, width = tiles[0].shape
    rows = int(np.ceil(len(tiles) / columns))
    sheet = np.zeros((rows * height, columns * width), dtype=np.uint8)
    for index, tile in enumerate(tiles):
        row, col = divmod(index, columns)
        sheet[row * height : (row + 1) * height, col * width : (col + 1) * width] = tile
    image = Image.fromarray(sheet, mode="L")
    if scale > 1:
        image = image.resize((sheet.shape[1] * scale, sheet.shape[0] * scale), Image.NEAREST)
    return image


def _write_preview(path: Path, frames: list[np.ndarray], fps: int) -> str | None:
    """Write an MP4 preview; return a warning string instead of failing collection."""
    try:
        import imageio.v2 as imageio

        prepared = []
        for frame in frames:
            array = np.asarray(frame)
            if array.ndim == 2:
                array = np.repeat(array[..., None], 3, axis=2)
            height, width = array.shape[:2]
            prepared.append(array[: height - height % 2, : width - width % 2])
        path.parent.mkdir(parents=True, exist_ok=True)
        imageio.mimwrite(str(path), prepared, fps=fps, macro_block_size=1)
    except Exception as exc:  # noqa: BLE001 - previews are a curation aid only
        return f"preview {path.name} not written: {exc}"
    return None


def collect_scenarios(resolved: ResolvedConfig) -> Path:
    """Roll out the collector checkpoint and write candidates plus a manifest template."""
    study = require_study(resolved, stage="collect-scenarios")
    cfg = study.scenarios
    collection = cfg.collection
    logger = get_logger("scenarios")
    extra = log_extra(stage="collect-scenarios", config_hash=resolved.config_hash)

    manifest_path = Path(cfg.manifest)
    if manifest_path.exists():
        raise ScenarioError(
            f"Scenario manifest already exists: {manifest_path}",
            context={
                "hint": "collection never overwrites a (possibly curated) manifest; "
                "move it aside or point scenarios.manifest at a new file"
            },
        )
    if not 0 <= collection.experiment_index < len(study.experiments):
        raise ScenarioError(
            "scenarios.collection.experiment_index is out of range",
            context={"index": collection.experiment_index, "experiments": len(study.experiments)},
        )
    run = load_run(Path(study.experiments[collection.experiment_index].run_dir), collection.experiment_index)
    overlap = sorted(set(collection.seeds) & run.evaluation_seeds)
    if overlap:
        raise ScenarioError(
            "Scenario collection seeds must be disjoint from evaluation seeds",
            context={"overlap": overlap, "run_id": run.run_id},
        )
    if run.observation_fingerprint is None:
        raise ScenarioError(
            f"Run {run.run_dir} has no environment_fingerprint.json",
            context={"hint": "re-run drl-sim train to regenerate run metadata"},
        )
    checkpoint = run.selected[collection.checkpoint]
    if not checkpoint.path.exists():
        raise CheckpointError(
            f"Selected {collection.checkpoint} checkpoint file is missing: {checkpoint.path}"
        )

    device = resolve_device(study.extraction.device)
    adapter = get_algorithm_adapter(run.algorithm.adapter)
    agent = adapter.load(checkpoint.path, run.algorithm, None, device=device)

    data_dir = scenario_data_dir(manifest_path)
    candidates_dir = data_dir / "candidates"
    (candidates_dir / "episodes").mkdir(parents=True, exist_ok=True)
    (candidates_dir / "contact_sheets").mkdir(parents=True, exist_ok=True)

    collector = _Collector(
        study=study,
        run=run,
        agent=agent,
        data_dir=data_dir,
        candidates_dir=candidates_dir,
    )
    logger.info(
        "collecting candidates from %s (%s) over %d seed(s)",
        run.run_id,
        checkpoint.checkpoint_id,
        len(collection.seeds),
        extra=extra,
    )
    try:
        for seed in collection.seeds:
            collector.collect_seed(int(seed))
    finally:
        collector.close()

    labels_by_clip = {record["clip_id"]: record["scenario"] for record in collector.records}
    splits = assign_splits(
        labels_by_clip, train_fraction=cfg.split.train_fraction, seed=cfg.split.seed
    )
    created_at = utc_now()
    clips = [
        ClipRecord(
            clip_id=record["clip_id"],
            scenario=record["scenario"],
            split=splits[record["clip_id"]],  # type: ignore[arg-type]
            source_episode_id=record["source_episode_id"],
            collection_seed=record["collection_seed"],
            start_step=record["start_step"],
            anchor_step=record["anchor_step"],
            end_step=record["end_step"],
            burn_in_steps=record["burn_in_steps"],
            anchor_event=record["anchor_event"],
            observation_key=record["clip_id"],
            observation_sha256=record["observation_sha256"],
            review_status="pending",
            curator=None,
            notes=record["notes"],
            created_at=created_at,
        )
        for record in collector.records
    ]
    manifest = ScenarioManifest(
        dataset_id=manifest_path.stem,
        environment_fingerprint=run.observation_fingerprint,
        collector=CollectorInfo(
            policy="checkpoint",
            run_id=run.run_id,
            capability=collection.checkpoint,
            checkpoint_id=checkpoint.checkpoint_id,
            checkpoint_sha256=sha256_file(checkpoint.path),
        ),
        created_at=created_at,
        clips=clips,
    )
    dump_manifest(manifest, manifest_path, header=_TEMPLATE_HEADER)

    counts = Counter(record["scenario"] for record in collector.records)
    summary = {
        "study_id": study.id,
        "config_hash": resolved.config_hash,
        "run_id": run.run_id,
        "collector_checkpoint": checkpoint.checkpoint_id,
        "manifest_template": str(manifest_path),
        "observations": str(data_dir / "observations.npz"),
        "episodes": collector.episode_summaries,
        "candidates_per_label": {label: int(counts.get(label, 0)) for label in cfg.labels},
        "skipped_windows": dict(sorted(collector.skipped.items())),
        "warnings": collector.warnings,
        "created_at": created_at,
    }
    (candidates_dir / "candidates.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True), encoding="utf-8"
    )

    for label in cfg.labels:
        found = int(counts.get(label, 0))
        if found < cfg.minimum_clips_per_label:
            logger.warning(
                "only %d candidate(s) for label %r (study needs %d approved)",
                found,
                label,
                cfg.minimum_clips_per_label,
                extra=extra,
            )
    for warning in collector.warnings:
        logger.warning(warning, extra=extra)
    logger.info(
        "wrote %d candidate clip(s) and manifest template %s",
        len(clips),
        manifest_path,
        extra=extra,
    )
    return data_dir


class _Collector:
    """Stateful rollout helper that streams candidate windows to disk."""

    def __init__(
        self,
        *,
        study: StudyConfig,
        run: RunInfo,
        agent: Any,
        data_dir: Path,
        candidates_dir: Path,
    ) -> None:
        cfg = study.scenarios
        self.study = study
        self.run = run
        self.agent = agent
        self.candidates_dir = candidates_dir
        self.clip_steps = cfg.clip_steps
        self.burn_in = cfg.burn_in_steps
        self.windows = cfg.collection.candidate_windows
        self.labels = list(cfg.labels)
        self.collection = cfg.collection
        self.need_rgb = cfg.collection.retain_source_rgb or cfg.collection.write_video_previews
        self.preview_fps = study.dashboard.charts.clip_fps if hasattr(study.dashboard, "charts") else 8
        # History needed to cut any configured window once its last step is reached.
        extra_history = max(
            [0, *[-(spec.offset_steps) - (self.clip_steps - 1) for spec in self.windows.values()]]
        )
        self.history = self.clip_steps + self.burn_in + extra_history
        self.observations = _NpzWriter(data_dir / "observations.npz")
        self.rgb: _NpzWriter | None = (
            _NpzWriter(candidates_dir / "source_rgb.npz")
            if cfg.collection.retain_source_rgb
            else None
        )
        self.records: list[dict[str, Any]] = []
        self.episode_summaries: list[dict[str, Any]] = []
        self.skipped: Counter[str] = Counter()
        self.warnings: list[str] = []
        self._label_counts: Counter[str] = Counter()
        self._checksums: set[str] = set()

    def close(self) -> None:
        self.observations.close()
        if self.rgb is not None:
            self.rgb.close()

    def collect_seed(self, seed: int) -> None:
        env = make_environment(
            self.run.environment,
            seed=seed,
            render_mode="rgb_array" if self.need_rgb else None,
        )
        try:
            for episode_index in range(self.collection.episodes_per_seed):
                if episode_index == 0:
                    observation, info = env.reset(seed=seed)
                else:
                    observation, info = env.reset()
                episode_id = (
                    f"{self.run.run_id}-{self.collection.checkpoint}-s{seed}-e{episode_index}"
                )
                self._rollout(env, observation, info, _EpisodeState(episode_id=episode_id, seed=seed))
        finally:
            env.close()

    def _rollout(self, env: Any, observation: Any, info: dict[str, Any], state: _EpisodeState) -> None:
        obs_history: dict[int, np.ndarray] = {}
        rgb_history: dict[int, np.ndarray] = {}
        pending: list[_PendingWindow] = []
        last_end: dict[str, int] = {}
        prev_lives = info.get("lives")
        life_start_step = 0
        done = False
        step = 0
        while not done and step < self.collection.max_agent_steps:
            obs_array = np.asarray(observation)
            obs_history[step] = obs_array.copy()
            if self.need_rgb:
                frame = env.render()
                if frame is not None:
                    rgb_history[step] = np.asarray(frame).copy()
            stale = step - self.history
            obs_history.pop(stale, None)
            rgb_history.pop(stale, None)

            action = self.agent.predict(obs_array, deterministic=True)
            action_value = int(np.asarray(action).reshape(-1)[0])
            observation, reward, terminated, truncated, info = env.step(action_value)
            lives = info.get("lives", prev_lives)
            lost_life = prev_lives is not None and lives is not None and lives < prev_lives

            state.actions.append(action_value)
            state.rewards.append(float(reward))
            state.lives.append(-1 if lives is None else int(lives))
            state.terminated.append(bool(terminated))
            state.truncated.append(bool(truncated))

            # A terminal step is a death only when the life counter did not already reach zero
            out_of_lives = lives is not None and lives <= 0
            events: list[str] = []
            if step == life_start_step:
                events.append("life_start")
            if lost_life or (terminated and not out_of_lives):
                events.append("life_lost")
                # No new life starts once the counter is exhausted
                life_start_step = -1 if out_of_lives else step + 1
            if reward > 0:
                events.append("positive_goal_event")
            if events:
                state.events[step] = events

            for label in self.labels:
                spec = self.windows[label]
                if spec.anchor not in events:
                    continue
                if spec.anchor == "positive_goal_event" and reward <= spec.min_reward:
                    continue
                start = step + spec.offset_steps
                end = start + self.clip_steps - 1
                if start < 0:
                    self.skipped[f"{label}:starts_before_episode"] += 1
                elif label in last_end and start <= last_end[label]:
                    self.skipped[f"{label}:overlaps_previous_candidate"] += 1
                elif end < step and start < step - self.history + 1:
                    self.skipped[f"{label}:window_outside_history"] += 1
                else:
                    last_end[label] = end
                    pending.append(
                        _PendingWindow(
                            label=label,
                            anchor_event=spec.anchor,
                            anchor_step=step,
                            anchor_reward=float(reward),
                            start=start,
                            end=end,
                        )
                    )

            still_pending: list[_PendingWindow] = []
            for window in pending:
                if window.end > step:
                    still_pending.append(window)
                    continue
                written = self._finalize(window, state, obs_history, rgb_history)
                if not written and last_end.get(window.label) == window.end:
                    # A discarded window must not block later candidates of its label.
                    del last_end[window.label]
            pending = still_pending

            prev_lives = lives
            done = bool(terminated or truncated)
            step += 1

        for window in pending:
            self.skipped[f"{window.label}:episode_ended_before_window"] += 1

        episode_path = self.candidates_dir / "episodes" / f"{state.episode_id}.npz"
        np.savez_compressed(
            episode_path,
            actions=np.asarray(state.actions, dtype=np.int64),
            rewards=np.asarray(state.rewards, dtype=np.float64),
            lives=np.asarray(state.lives, dtype=np.int64),
            terminated=np.asarray(state.terminated, dtype=bool),
            truncated=np.asarray(state.truncated, dtype=bool),
        )
        self.episode_summaries.append(
            {
                "episode_id": state.episode_id,
                "collection_seed": state.seed,
                "length": len(state.actions),
                "return": float(np.sum(state.rewards)) if state.rewards else 0.0,
                "events": {
                    name: int(sum(name in names for names in state.events.values()))
                    for name in ANCHOR_EVENTS
                },
                "trajectory": episode_path.name,
            }
        )

    def _finalize(
        self,
        window: _PendingWindow,
        state: _EpisodeState,
        obs_history: dict[int, np.ndarray],
        rgb_history: dict[int, np.ndarray],
    ) -> bool:
        """Write one candidate window; return False when it is discarded."""
        label = window.label
        window_events = {
            step: names for step, names in state.events.items() if window.start <= step <= window.end
        }
        if window.anchor_event == "life_start" and any(
            "life_lost" in names for names in window_events.values()
        ):
            # A life that ends inside the window is not a pre-outcome baseline.
            self.skipped[f"{label}:life_lost_inside_window"] += 1
            return False
        if any(step not in obs_history for step in range(window.start, window.end + 1)):
            self.skipped[f"{label}:window_outside_history"] += 1
            return False
        burn_in = 0
        while (
            burn_in < self.burn_in
            and window.start - burn_in - 1 >= 0
            and (window.start - burn_in - 1) in obs_history
        ):
            burn_in += 1
        steps = range(window.start - burn_in, window.end + 1)
        frames = np.stack([obs_history[step] for step in steps], axis=0)

        # A deterministic policy and emulator can replay the same frames under another seed
        checksum = observation_sha256(frames)
        if checksum in self._checksums:
            self.skipped[f"{label}:duplicate_observations"] += 1
            return False
        self._checksums.add(checksum)

        self._label_counts[label] += 1
        clip_id = f"{label}-{self._label_counts[label]:04d}"
        self.observations.add(clip_id, frames)

        rgb_frames = [rgb_history[step] for step in steps if step in rgb_history]
        if self.rgb is not None and len(rgb_frames) == len(steps):
            self.rgb.add(clip_id, np.stack(rgb_frames, axis=0))
        _contact_sheet(frames[burn_in:]).save(
            self.candidates_dir / "contact_sheets" / f"{clip_id}.png"
        )
        if self.collection.write_video_previews:
            preview_frames = (
                rgb_frames[burn_in:]
                if len(rgb_frames) == len(steps)
                else [_newest_frame(frame) for frame in frames[burn_in:]]
            )
            warning = _write_preview(
                self.candidates_dir / "previews" / f"{clip_id}.mp4",
                preview_frames,
                fps=int(self.preview_fps),
            )
            if warning:
                self.warnings.append(warning)

        event_text = "; ".join(
            f"{name}@{step}" for step, names in sorted(window_events.items()) for name in names
        )
        window_return = float(sum(state.rewards[window.start : window.end + 1]))
        self.records.append(
            {
                "clip_id": clip_id,
                "scenario": label,
                "source_episode_id": state.episode_id,
                "collection_seed": state.seed,
                "start_step": window.start,
                "anchor_step": window.anchor_step,
                "end_step": window.end,
                "burn_in_steps": burn_in,
                "anchor_event": window.anchor_event,
                "observation_sha256": checksum,
                "notes": (
                    f"auto-candidate; anchor_reward={window.anchor_reward:g}; "
                    f"window_return={window_return:g}; events: {event_text or 'none'}"
                ),
            }
        )
        return True
